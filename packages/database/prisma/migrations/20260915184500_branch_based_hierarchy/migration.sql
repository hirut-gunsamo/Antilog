-- Branch-based hierarchy.
--
-- Moves from the old "one user per StockLocation" + "Sales -> Supervisor" model to:
--   StockLocation (branch) 1 --- many User
--   OWNER has no branch (branchId IS NULL); SUPERVISOR and SALES belong to one branch.
--   A SALES user's supervisor is derived: the active SUPERVISOR of the same branch.
--
-- This migration is data-preserving. No table is dropped and no row is deleted.
-- Two columns are dropped (StockLocation.userId, User.supervisorId); the values in
-- both are archived into AuditLog in step 1 below before they are removed.

-- ---------------------------------------------------------------------------
-- 1. Archive the relationships we are about to drop, so they are recoverable
--    from inside the database itself (not only from the pg_dump backup).
-- ---------------------------------------------------------------------------

-- Old Sales -> Supervisor links.
INSERT INTO "AuditLog" ("id", "actorId", "action", "entityType", "entityId", "oldData")
SELECT
  gen_random_uuid()::text,
  NULL,
  'MIGRATION_ARCHIVE_SUPERVISOR_LINK',
  'User',
  u."id",
  jsonb_build_object(
    'userId', u."id",
    'userName', u."name",
    'userEmail', u."email",
    'role', u."role"::text,
    'supervisorId', u."supervisorId",
    'supervisorName', s."name",
    'supervisorEmail', s."email"
  )
FROM "User" u
LEFT JOIN "User" s ON s."id" = u."supervisorId"
WHERE u."supervisorId" IS NOT NULL;

-- Old StockLocation -> owning User links.
INSERT INTO "AuditLog" ("id", "actorId", "action", "entityType", "entityId", "oldData")
SELECT
  gen_random_uuid()::text,
  NULL,
  'MIGRATION_ARCHIVE_LOCATION_USER',
  'StockLocation',
