ALTER TABLE "User" ADD CONSTRAINT "User_branchId_fkey" FOREIGN KEY ("branchId") REFERENCES "StockLocation"("id") ON DELETE SET NULL ON UPDATE CASCADE;

-- ---------------------------------------------------------------------------
-- 3. Seed the new branch metadata.
--    Hawassa Main is the main stock source and also a normal selling branch.
-- ---------------------------------------------------------------------------

UPDATE "StockLocation" SET "isMainStock" = true WHERE "name" = 'Hawassa Main';

-- Fail loudly rather than silently leaving an existing system with no main
-- stock source.
--
-- A database with no branches at all is a new installation rather than a
-- system being converted: its Owner creates the branches in the app, where
-- the same rules are enforced. Checking there would refuse every fresh
-- install for not already holding data it was never given.
DO $$
DECLARE
  main_count INT;
  branch_count INT;
BEGIN
  SELECT COUNT(*) INTO branch_count FROM "StockLocation";

  IF branch_count = 0 THEN
    RAISE NOTICE 'No branches yet: new installation, nothing to convert.';
    RETURN;
  END IF;

  SELECT COUNT(*) INTO main_count FROM "StockLocation" WHERE "isMainStock" = true;
  IF main_count <> 1 THEN
    RAISE EXCEPTION
      'Expected exactly 1 main stock branch, found %. Check that a branch named "Hawassa Main" exists.',
      main_count;
  END IF;

  IF branch_count < 4 THEN
    RAISE EXCEPTION
      'Expected at least 4 branches (Hawassa Main, Balela, Bensa Daye, Arroresa), found %.',
      branch_count;
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 4. Enforce the org structure at the database level:
--      1 OWNER (no branch)  ->  4 branches  ->  1 active SUPERVISOR each
--                                            ->  many SALES each
--
--    These are raw-SQL guards because Prisma's schema language cannot express
--    partial unique indexes or CHECK constraints. Both have been verified to
--    produce no schema drift (`prisma migrate diff` reports an empty diff).
-- ---------------------------------------------------------------------------

-- At most ONE active SUPERVISOR per branch.
-- Partial index, so it does not restrict:
--   - deactivated supervisors (isActive = false) -> predecessors are retained
--   - SALES users                                -> unlimited per branch
--   - supervisors not yet assigned (branchId IS NULL, distinct under NULL)
CREATE UNIQUE INDEX "User_one_active_supervisor_per_branch"
  ON "User" ("branchId")
  WHERE "role" = 'SUPERVISOR' AND "isActive" = true;

-- The OWNER is org-wide and must never belong to a branch.
ALTER TABLE "User"
  ADD CONSTRAINT "User_owner_has_no_branch"
  CHECK ("role" <> 'OWNER' OR "branchId" IS NULL);

