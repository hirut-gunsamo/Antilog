const DICTS: Record<Lang, Record<TranslationKey, string>> = { en, am }

function isLang(value: unknown): value is Lang {
  return typeof value === 'string' && (LANGS as readonly string[]).includes(value)
}

export function readLang(): Lang {
  try {
    const stored = localStorage.getItem(KEY)
    return isLang(stored) ? stored : 'en'
  } catch {
    // Private windows and blocked site data both throw here.
    return 'en'
  }
}

export function storeLang(lang: Lang) {
  // Screen readers and hyphenation rules key off this.
  document.documentElement.lang = lang

  try {
    localStorage.setItem(KEY, lang)
  } catch {
    // Not fatal: the choice simply will not survive a reload.
  }
}

/** Fills {placeholders} from `vars`. */
export function translate(
  lang: Lang,
  key: TranslationKey,
  vars?: Record<string, string | number>,
) {
  const template = DICTS[lang][key] ?? en[key] ?? key

  if (!vars) return template

  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in vars ? String(vars[name]) : whole,
  )
}

export type Translate = (
  key: TranslationKey,
  vars?: Record<string, string | number>,
) => string

export const LanguageContext = createContext<{
  lang: Lang
  setLang: (lang: Lang) => void
  t: Translate
}>({
  lang: 'en',
  setLang: () => {},
  t: (key, vars) => translate('en', key, vars),
})

export function useLang() {
  return useContext(LanguageContext)
}

/** Shorthand for components that only need the lookup. */
export function useT(): Translate {
  return useContext(LanguageContext).t
}
